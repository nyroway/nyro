export const messageCatalogs: Record<Locale, Record<MessageKey, string>> = {
  "en-US": enUS,
  "zh-CN": zhCN,
};

export function resolveInitialLocale(saved: string | null | undefined): Locale {
  return saved === "zh-CN" || saved === "en-US" ? saved : "en-US";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number> = {},
): string {
  const template = messageCatalogs[locale]?.[key] ?? messageCatalogs["en-US"][key];
  return Object.entries(params).reduce(
    (value, [name, replacement]) => value.split(`{${name}}`).join(String(replacement)),
    template,
  );
}

export function localizedMessage(
  isZh: boolean,
  key: MessageKey,
  params: Record<string, string | number> = {},
): string {
  return translate(isZh ? "zh-CN" : "en-US", key, params);
}
